"use client";

/**
 * SpeakEasy 2.0 移动端主界面：三 Tab 单页 + 深链（?tab=&friend=）。
 *
 * 数据全部来自 `/api/v2`；后端未就绪/出错时降级为空态 + 中文提示，绝不白屏。
 */

import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { Plus, RefreshCw, WifiOff } from "lucide-react";

import { ChatsTab } from "@/components/v2/ChatsTab";
import { ChatView } from "@/components/v2/ChatView";
import { DiscoverTab } from "@/components/v2/DiscoverTab";
import { NotesTab } from "@/components/v2/NotesTab";
import { TabBar } from "@/components/v2/TabBar";
import { ToastProvider, useToast } from "@/components/v2/Toast";
import { api } from "@/lib/v2/api";
import {
  emptyFactSheet,
  type Expression,
  type FactSheet,
  type Friend,
  type MemoryPayload,
  type Moment,
  type Tab,
} from "@/lib/v2/types";
import { errorText } from "@/lib/v2/format";
import type { RecordingResult } from "@/lib/v2/useRecorder";

const FRIEND_POLL_MS = 10_000;

const TAB_TITLES: Record<Tab, string> = {
  chats: "SpeakEasy",
  discover: "动态 · 偶遇",
  notes: "表达本 · 画像",
};

function upsertFriend(list: Friend[], friend: Friend): Friend[] {
  const index = list.findIndex((item) => item.id === friend.id);
  if (index < 0) return [friend, ...list];
  const next = [...list];
  next[index] = { ...next[index], ...friend };
  return next;
}

function isTab(value: string | null): value is Tab {
  return value === "chats" || value === "discover" || value === "notes";
}

function AppInner() {
  const { showToast } = useToast();

  const [tab, setTab] = useState<Tab>("chats");
  const [activeFriend, setActiveFriend] = useState<Friend | null>(null);

  const [friends, setFriends] = useState<Friend[]>([]);
  const [requests, setRequests] = useState<Friend[]>([]);
  const [bootLoading, setBootLoading] = useState(true);
  const [bootError, setBootError] = useState<string | null>(null);
  const [profileName, setProfileName] = useState("");
  const [llmMock, setLlmMock] = useState(false);
  // 首次启动后端在后台捏人：此时加速轮询并给出"正在安排朋友"的提示
  const [onboardingPending, setOnboardingPending] = useState(false);

  const [moments, setMoments] = useState<Moment[]>([]);
  const [momentsLoading, setMomentsLoading] = useState(false);
  const [momentsError, setMomentsError] = useState<string | null>(null);
  const [momentsLoaded, setMomentsLoaded] = useState(false);
  const [generating, setGenerating] = useState(false);

  const [discovering, setDiscovering] = useState(false);
  const [acceptingId, setAcceptingId] = useState<string | null>(null);

  const [expressions, setExpressions] = useState<Expression[]>([]);
  const [expressionsLoading, setExpressionsLoading] = useState(false);
  const [expressionsError, setExpressionsError] = useState<string | null>(null);
  const [expressionsLoaded, setExpressionsLoaded] = useState(false);

  const [memories, setMemories] = useState<MemoryPayload | null>(null);
  const [memoriesLoading, setMemoriesLoading] = useState(false);
  const [memoriesError, setMemoriesError] = useState<string | null>(null);
  const [memoriesLoaded, setMemoriesLoaded] = useState(false);

  const mountedRef = useRef(true);
  const pendingFriendIdRef = useRef<string | null>(null);
  const autoGeneratedRef = useRef(false);
  const urlReadyRef = useRef(false);

  /* ------------------------------------------------------------ 深链初始化 */

  // PWA：仅生产构建注册 Service Worker（dev 下避免缓存干扰开发）
  useEffect(() => {
    if (process.env.NODE_ENV !== "production") return;
    if (typeof navigator === "undefined" || !("serviceWorker" in navigator)) return;
    const timer = setTimeout(() => {
      navigator.serviceWorker.register("/sw.js").catch(() => undefined);
    }, 1200);
    return () => clearTimeout(timer);
  }, []);

  useEffect(() => {
    mountedRef.current = true;
    try {
      const params = new URLSearchParams(window.location.search);
      const rawTab = params.get("tab");
      if (isTab(rawTab)) setTab(rawTab);
      const friendId = params.get("friend");
      if (friendId) pendingFriendIdRef.current = friendId;
    } catch {
      /* 忽略非法 URL */
    }
    urlReadyRef.current = true;
    return () => {
      mountedRef.current = false;
    };
  }, []);

  /** Tab / 聊天对象变化时同步 query，便于截图与分享。 */
  useEffect(() => {
    if (!urlReadyRef.current) return;
    try {
      const params = new URLSearchParams(window.location.search);
      params.set("tab", tab);
      if (activeFriend) params.set("friend", activeFriend.id);
      else params.delete("friend");
      const next = `${window.location.pathname}?${params.toString()}`;
      window.history.replaceState(null, "", next);
    } catch {
      /* 忽略 replaceState 异常 */
    }
  }, [tab, activeFriend]);

  /* ------------------------------------------------------------ 首屏数据 */

  const applyBootstrapFriend = useCallback((list: Friend[]) => {
    const pendingId = pendingFriendIdRef.current;
    if (!pendingId) return;
    const found = list.find((friend) => friend.id === pendingId);
    if (found) {
      setActiveFriend(found);
      pendingFriendIdRef.current = null;
      return;
    }
    // 列表里没有（可能是待通过申请或直接深链了陌生 id）→ 单独拉详情
    void api
      .friend(pendingId)
      .then((friend) => {
        if (!mountedRef.current) return;
        setActiveFriend(friend);
        setFriends((prev) => upsertFriend(prev, friend));
      })
      .catch(() => undefined)
      .finally(() => {
        pendingFriendIdRef.current = null;
      });
  }, []);

  const loadBootstrap = useCallback(
    async (silent = false) => {
      if (!silent) {
        setBootLoading(true);
        setBootError(null);
      }
      try {
        const payload = await api.bootstrap();
        if (!mountedRef.current) return;
        setFriends(payload.friends);
        setRequests(payload.requests);
        setProfileName(payload.profile.nickname);
        setLlmMock(payload.llm_mock);
        setOnboardingPending(payload.pending_onboarding);
        setBootError(null);
        applyBootstrapFriend(payload.friends);
      } catch (err) {
        if (!mountedRef.current) return;
        if (!silent) setBootError(errorText(err));
      } finally {
        if (mountedRef.current && !silent) setBootLoading(false);
      }
    },
    [applyBootstrapFriend],
  );

  useEffect(() => {
    void loadBootstrap();
  }, [loadBootstrap]);

  /* ------------------------------------------------------------ 好友轮询 */

  useEffect(() => {
    if (activeFriend) return;
    const interval = onboardingPending ? 2500 : FRIEND_POLL_MS;
    const timer = setInterval(() => {
      void (async () => {
        try {
          const payload = await api.friends();
          if (!mountedRef.current) return;
          setFriends(Array.isArray(payload.friends) ? payload.friends : []);
          setRequests(Array.isArray(payload.requests) ? payload.requests : []);
          if (payload.friends.length > 0) setOnboardingPending(false);
        } catch {
          /* 轮询失败静默，保留现有数据 */
        }
      })();
    }, interval);
    return () => clearInterval(timer);
  }, [activeFriend, onboardingPending]);

  /* ------------------------------------------------------------ 动态数据 */

  const loadMoments = useCallback(async () => {
    setMomentsLoading(true);
    setMomentsError(null);
    try {
      const list = await api.moments();
      if (!mountedRef.current) return;
      setMoments(list);
      if (list.length === 0 && !autoGeneratedRef.current) {
        autoGeneratedRef.current = true;
        setGenerating(true);
        try {
          const generated = await api.generateMoments();
          if (!mountedRef.current) return;
          setMoments(generated);
        } catch {
          /* 生成失败保留空态 */
        } finally {
          if (mountedRef.current) setGenerating(false);
        }
      }
    } catch (err) {
      if (!mountedRef.current) return;
      setMomentsError(errorText(err));
    } finally {
      if (mountedRef.current) {
        setMomentsLoading(false);
        setMomentsLoaded(true);
      }
    }
  }, []);

  useEffect(() => {
    if (tab !== "discover" || momentsLoaded || momentsLoading) return;
    void loadMoments();
  }, [tab, momentsLoaded, momentsLoading, loadMoments]);

  const handleGenerate = useCallback(async () => {
    setGenerating(true);
    setMomentsError(null);
    try {
      const generated = await api.generateMoments();
      if (!mountedRef.current) return;
      setMoments(generated);
      showToast(generated.length > 0 ? "好友们发新动态了 🌤️" : "今天暂时没有新动态", "success");
    } catch (err) {
      showToast(`生成动态失败：${errorText(err)}`, "error");
    } finally {
      if (mountedRef.current) setGenerating(false);
    }
  }, [showToast]);

  /* ------------------------------------------------------------ 表达本 / 记忆 */

  const loadExpressions = useCallback(async () => {
    setExpressionsLoading(true);
    setExpressionsError(null);
    try {
      const list = await api.expressions();
      if (!mountedRef.current) return;
      setExpressions(list);
    } catch (err) {
      if (!mountedRef.current) return;
      setExpressionsError(errorText(err));
    } finally {
      if (mountedRef.current) {
        setExpressionsLoading(false);
        setExpressionsLoaded(true);
      }
    }
  }, []);

  const loadMemories = useCallback(async () => {
    setMemoriesLoading(true);
    setMemoriesError(null);
    try {
      const payload = await api.memories();
      if (!mountedRef.current) return;
      setMemories(payload);
    } catch (err) {
      if (!mountedRef.current) return;
      setMemoriesError(errorText(err));
    } finally {
      if (mountedRef.current) {
        setMemoriesLoading(false);
        setMemoriesLoaded(true);
      }
    }
  }, []);

  useEffect(() => {
    if (tab !== "notes") return;
    if (!expressionsLoaded && !expressionsLoading) void loadExpressions();
    if (!memoriesLoaded && !memoriesLoading) void loadMemories();
  }, [tab, expressionsLoaded, expressionsLoading, loadExpressions, memoriesLoaded, memoriesLoading, loadMemories]);

  const handleToggleExpression = useCallback(
    async (expression: Expression) => {
      const nextStatus = expression.status === "mastered" ? "learning" : "mastered";
      try {
        await api.patchExpression(expression.id, { status: nextStatus });
        setExpressions((prev) =>
          prev.map((item) => (item.id === expression.id ? { ...item, status: nextStatus } : item)),
        );
        showToast(nextStatus === "mastered" ? "已标记掌握 ✓" : "已移回待掌握", "success");
      } catch (err) {
        showToast(`更新失败：${errorText(err)}`, "error");
        throw err;
      }
    },
    [showToast],
  );

  const handleDeleteExpression = useCallback(
    async (expression: Expression) => {
      try {
        await api.deleteExpression(expression.id);
        setExpressions((prev) => prev.filter((item) => item.id !== expression.id));
        showToast("已删除该表达", "success");
      } catch (err) {
        showToast(`删除失败：${errorText(err)}`, "error");
        throw err;
      }
    },
    [showToast],
  );

  const handleSaveMemories = useCallback(
    async (patch: { nickname: string; city: string; majorOrJob: string; interests: string[]; weaknesses: string[] }) => {
      const baseFact = memories?.fact_sheet ?? emptyFactSheet();
      const fact: FactSheet = {
        ...baseFact,
        profile: {
          ...baseFact.profile,
          nickname: patch.nickname,
          city: patch.city,
          major_or_job: patch.majorOrJob,
        },
        interests: patch.interests,
        language_profile: {
          ...baseFact.language_profile,
          weaknesses: patch.weaknesses,
        },
      };
      try {
        const payload = await api.putMemories({ nickname: patch.nickname, fact_sheet: fact });
        if (!mountedRef.current) return;
        // 后端可能返回 204 / 不完整数据：本地合并兜底
        const merged: MemoryPayload = {
          profile: {
            ...(memories?.profile ?? { nickname: "", native_language: "zh", target_languages: ["en"], fact_sheet: fact }),
            nickname: patch.nickname || payload.profile.nickname,
            fact_sheet: fact,
          },
          fact_sheet: fact,
          friends: payload.friends.length > 0 ? payload.friends : memories?.friends ?? [],
        };
        setMemories(merged);
        showToast("记忆卡已保存", "success");
      } catch (err) {
        showToast(`保存失败：${errorText(err)}`, "error");
        throw err;
      }
    },
    [memories, showToast],
  );

  /* ------------------------------------------------------------ 好友社交动作 */

  const openChat = useCallback((friend: Friend) => {
    setActiveFriend(friend);
    setTab("chats");
    setFriends((prev) => prev.map((item) => (item.id === friend.id ? { ...item, unread: 0 } : item)));
  }, []);

  const handleBackFromChat = useCallback(() => {
    setActiveFriend(null);
    void loadBootstrap(true);
  }, [loadBootstrap]);

  const handleAccept = useCallback(
    async (friend: Friend) => {
      setAcceptingId(friend.id);
      try {
        const response = await api.acceptFriend(friend.id);
        if (!mountedRef.current) return;
        setRequests((prev) => prev.filter((item) => item.id !== friend.id));
        setFriends((prev) => upsertFriend(prev, response.friend));
        showToast(`已通过 ${response.friend.name} 的好友申请 🎉`, "success");
        openChat(response.friend);
      } catch (err) {
        showToast(`接受失败：${errorText(err)}`, "error");
      } finally {
        if (mountedRef.current) setAcceptingId(null);
      }
    },
    [openChat, showToast],
  );

  const handleDecline = useCallback(
    async (friend: Friend) => {
      setRequests((prev) => prev.filter((item) => item.id !== friend.id));
      try {
        await api.declineFriend(friend.id);
        showToast(`已忽略 ${friend.name} 的申请`, "success");
      } catch (err) {
        showToast(`忽略失败：${errorText(err)}`, "error");
        void loadBootstrap(true);
      }
    },
    [loadBootstrap, showToast],
  );

  const handleDiscover = useCallback(
    async (filters: { nationality: string; language: string; gender: string }) => {
      setDiscovering(true);
      try {
        const response = await api.discover(filters);
        if (!mountedRef.current) return;
        setFriends((prev) => upsertFriend(prev, response.friend));
        showToast(`${response.friend.name} 来打招呼了 👋`, "success");
        openChat(response.friend);
      } catch (err) {
        showToast(`偶遇失败：${errorText(err)}`, "error");
      } finally {
        if (mountedRef.current) setDiscovering(false);
      }
    },
    [openChat, showToast],
  );

  const handleCommentVoice = useCallback(
    async (moment: Moment, result: RecordingResult) => {
      try {
        const response = await api.commentMomentVoice(moment.id, result.blob, result.durationMs, result.filename);
        if (!mountedRef.current) return;
        setMoments((prev) => prev.map((item) => (item.id === moment.id ? { ...item, replied: true } : item)));
        const targetId = response.friend_id || moment.friend_id;
        let target: Friend | null = friends.find((friend) => friend.id === targetId) ?? null;
        if (!target) {
          // 朋友圈里的 friend 是精简对象，补一次详情以获得当地时间/熟稔度等字段
          try {
            target = await api.friend(targetId);
          } catch {
            target = moment.friend;
          }
        }
        showToast("评论已发送，话题带进私聊了 💬", "success");
        if (target) openChat(target);
      } catch (err) {
        showToast(`评论失败：${errorText(err)}`, "error");
      }
    },
    [friends, openChat, showToast],
  );

  /* ------------------------------------------------------------ 刷新 */

  const handleRefresh = useCallback(() => {
    if (tab === "chats") {
      void loadBootstrap();
      showToast("正在刷新好友列表…", "info");
    } else if (tab === "discover") {
      setMomentsLoaded(false);
      setMomentsError(null);
      void loadBootstrap(true);
      showToast("正在刷新动态…", "info");
    } else {
      setExpressionsLoaded(false);
      setMemoriesLoaded(false);
      showToast("正在刷新表达本与记忆…", "info");
    }
  }, [loadBootstrap, showToast, tab]);

  const unreadTotal = useMemo(() => friends.reduce((sum, friend) => sum + friend.unread, 0), [friends]);

  const handleTabChange = useCallback((next: Tab) => {
    setTab(next);
  }, []);

  /* ------------------------------------------------------------ 渲染 */

  const headerTitle = TAB_TITLES[tab];

  return (
    <div className="se-app">
      {activeFriend ? (
        <ChatView
          friend={activeFriend}
          onBack={handleBackFromChat}
          onFriendRefresh={(updated) => {
            setActiveFriend(updated);
            setFriends((prev) => upsertFriend(prev, updated));
          }}
        />
      ) : (
        <>
          <header className="se-header">
            <div className="se-header-side">
              {llmMock ? (
                <span className="se-mock-chip" title="后端未配置 LLM Key，当前由本地规则引擎回复">
                  演示模式
                </span>
              ) : null}
            </div>
            <div className="se-header-title">
              <h1>{headerTitle}</h1>
              {tab === "chats" && profileName ? <span className="se-header-greet">Hi, {profileName}</span> : null}
            </div>
            <div className="se-header-side right">
              <button type="button" onClick={handleRefresh} aria-label="刷新" className="se-header-icon">
                <RefreshCw size={17} />
              </button>
              <button type="button" onClick={() => handleTabChange("discover")} aria-label="偶遇新朋友" className="se-header-icon">
                <Plus size={19} />
              </button>
            </div>
          </header>

          <main className="se-main">
            {tab === "chats" && onboardingPending && friends.length === 0 ? (
              <div className="mx-3 mt-3 flex items-center gap-2 rounded-lg bg-white px-3 py-2.5 text-[12px] text-[color:var(--se-dim)] shadow-sm">
                <span className="se-rec-dot" aria-hidden />
                正在为你安排第一位外国朋友（首次启动需要十几秒）…
              </div>
            ) : null}

            {tab === "chats" ? (
              <ChatsTab
                friends={friends}
                requests={requests}
                loading={bootLoading}
                error={bootError}
                onRetry={() => void loadBootstrap()}
                onOpenChat={openChat}
                onAccept={(friend) => void handleAccept(friend)}
                onDecline={(friend) => void handleDecline(friend)}
                onExplore={() => handleTabChange("discover")}
                acceptingId={acceptingId}
              />
            ) : null}

            {tab === "discover" ? (
              <DiscoverTab
                requests={requests}
                moments={moments}
                loading={bootLoading}
                momentsLoading={momentsLoading}
                error={momentsError}
                discovering={discovering}
                generating={generating}
                acceptingId={acceptingId}
                onDiscover={(filters) => void handleDiscover(filters)}
                onGenerate={() => void handleGenerate()}
                onRetry={() => {
                  setMomentsLoaded(false);
                  setMomentsError(null);
                }}
                onAccept={(friend) => void handleAccept(friend)}
                onDecline={(friend) => void handleDecline(friend)}
                onCommentVoice={handleCommentVoice}
                onOpenChat={openChat}
              />
            ) : null}

            {tab === "notes" ? (
              <NotesTab
                expressions={expressions}
                expressionsLoading={expressionsLoading}
                expressionsError={expressionsError}
                onReloadExpressions={() => void loadExpressions()}
                onToggleExpression={handleToggleExpression}
                onDeleteExpression={handleDeleteExpression}
                memories={memories}
                memoriesLoading={memoriesLoading}
                memoriesError={memoriesError}
                onReloadMemories={() => void loadMemories()}
                onSaveMemories={handleSaveMemories}
              />
            ) : null}

            {bootError && tab === "chats" && friends.length === 0 ? (
              <div className="mt-2 flex items-center justify-center gap-1.5 text-[11px] text-[color:var(--se-faint)]">
                <WifiOff size={12} />
                后端 2.0 服务未连接，稍后会自动重试
              </div>
            ) : null}
          </main>

          <TabBar tab={tab} unread={unreadTotal} requests={requests.length} onChange={handleTabChange} />
        </>
      )}
    </div>
  );
}

export function SpeakEasyApp() {
  return (
    <ToastProvider>
      <AppInner />
    </ToastProvider>
  );
}
